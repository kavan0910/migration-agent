"""Phase C shared data contracts (frozen: C-01..C-08 all code against these).

Files (all under the project folder):
  feedback/findings.json      FindingsFile    written by the Verifier (C-01/C-02/C-09)
  feedback/resolutions.json   ResolutionsFile written by the resolution engine (C-03)
  feedback/comments.json      CommentsFile    written by the comment system (C-05)
  docs/changelog.md           generated by C-08
"""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

FindingKind = Literal["contradiction", "doc_only", "code_only", "doc_vs_doc"]
Severity = Literal["low", "medium", "high"]
ResolutionStatus = Literal["open", "accepted_doc", "accepted_code", "dismissed", "needs_reanalysis", "resolved"]


class Quote(BaseModel):
    """A verbatim passage. `source` is "understanding" (the generated doc) or a user_docs file path."""
    source: str
    text: str
    anchor: str = ""          # section anchor in the converted markdown, if known
    verified: bool = False    # set by C-09 string check against the real text


class Finding(BaseModel):
    id: str                   # F-0001, stable within a findings file
    kind: FindingKind
    severity: Severity = "low"
    title: str
    detail: str = ""
    item_ids: list[str] = Field(default_factory=list)   # graph IDs (COMP-0001, RULE-0003 ...)
    quotes: list[Quote] = Field(default_factory=list)
    area: str = ""            # grouping key for code_only findings (module/directory)


class FindingsFile(BaseModel):
    schema_version: int = 1
    graph_version: int = 0
    findings: list[Finding] = Field(default_factory=list)
    dropped_unverifiable: int = 0     # C-09: findings dropped because a quote did not verify
    claims_extracted: int = 0


class Resolution(BaseModel):
    finding_id: str
    status: ResolutionStatus
    note: str = ""
    affected_node_ids: list[str] = Field(default_factory=list)
    created: str = ""                  # ISO timestamp


class ResolutionsFile(BaseModel):
    schema_version: int = 1
    resolutions: list[Resolution] = Field(default_factory=list)


class Comment(BaseModel):
    id: str                   # CM-0001
    item_id: str              # graph ID the comment attaches to
    text: str
    author: str = "user"
    created: str = ""
    processed: bool = False   # True once targeted re-analysis consumed it


class CommentsFile(BaseModel):
    schema_version: int = 1
    comments: list[Comment] = Field(default_factory=list)
